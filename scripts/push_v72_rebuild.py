"""Push a FRESHLY BUILT, unmodified v7.2 as a control on the builder itself.

Both new arms land near 28.6 while the banked control sits near 30.0, and they share one thing the
control does not: they were generated by a builder that has been edited repeatedly since the control
kernel was pushed. The cache crop, the DFS budget knob, the fair-scheduling patch and the cell-parse
guard all landed in between. If any of those quietly changed the default path, every new arm would
sit below an old control and we would read it as the lever failing.

There is a competing explanation, that the control series is drifting down on its own: its first
seven draws averaged 30.44 and its last four 29.20. This submission separates the two. A fresh build
with NO knobs set is byte-for-byte the same configuration as the banked control. If it scores near
29.2 the builder is clean and the drift is real. If it scores near 28.6 the builder is the confound
and the last four arms were never measured against a fair baseline.

Usage: python push_v72_rebuild.py
"""
import json
import os
import shutil
import sys
import time

# A KAGGLE_API_TOKEN variable appeared in the rig's environment in early September carrying a
# different token from ~/.kaggle/access_token, and kaggle 2.x prefers the variable, so every call
# here died with "Authentication required". The file is the credential this project manages.
if os.path.isfile(os.path.join(os.path.expanduser("~"), ".kaggle", "access_token")):
    os.environ.pop("KAGGLE_API_TOKEN", None)
from kaggle.api.kaggle_api_extended import KaggleApi

BASE = os.environ.get("ARC_PROBE_BASE", r"D:\arc")
WORK = os.path.join(BASE, "_kpush72rb")
NB = "arc-agi-2-v7-2-rebuild-control.ipynb"   # the pushed copy carried a stale v7.7 name, same bytes
SRC = os.path.join(BASE, "notebooks", "arc_submission_v7_2.ipynb")
SLUG = "rc7530/arc-agi-2-v7-2-rebuild-control"   # must match what the TITLE slugs to
UTIL = "rc7530/pip-install-unsloth-flash-patch"


def main():
    assert os.path.isfile(SRC), "build it first: python build_v7_from_architects.py v7.2 (%s)" % SRC
    os.makedirs(WORK, exist_ok=True)
    shutil.copy(SRC, os.path.join(WORK, NB))

    meta = {
        "id": SLUG,
        "title": "ARC AGI 2 v7 2 rebuild control",
        "code_file": NB,
        "language": "python",
        "kernel_type": "notebook",
        "is_private": True,
        "enable_gpu": True,
        # REQUIRED, and its absence is silent. Without it the kernel gets machine_shape "Gpu" and
        # Kaggle may allocate a Tesla P100 (sm_60), on which this stack dies with "no kernel image is
        # available for execution on the device" -- torch 2.8+cu128 supports sm_70 and up. The
        # SCORING rerun uses L4s and would have been fine; it is the commit run that fails, and a
        # kernel whose commit fails has no output and therefore cannot be submitted at all.
        # v7-2-replicate carries NvidiaL4, which is where this string came from.
        "machine_shape": "NvidiaL4",
        "enable_internet": False,
        "dataset_sources": [],
        "competition_sources": ["arc-prize-2026-arc-agi-2"],
        "kernel_sources": [UTIL],
        # Exactly the string the working kernels carry, pulled from v7-2-replicate's own metadata.
        # The mirza mirror path and a lowercase "transformers" are both REJECTED as an invalid
        # model source, and the push still succeeds when they are, leaving a kernel with no model
        # attached and a run that fails at the assert. Check invalidModelSources in the response.
        "model_sources": ["sorokin/qwen3_4b_grids15_sft139/Transformers/bfloat16/1"],
    }
    json.dump(meta, open(os.path.join(WORK, "kernel-metadata.json"), "w"), indent=1)

    api = KaggleApi()
    api.authenticate()
    print("pushing %s" % SLUG, flush=True)
    r = api.kernels_push(WORK)
    print(r, flush=True)
    bad = getattr(r, "invalidModelSources", None) or (r.get("invalidModelSources")
                                                      if isinstance(r, dict) else None)
    if not bad:
        try:
            bad = json.loads(str(r)).get("invalidModelSources")
        except Exception:
            bad = None
    assert not bad, "model source rejected: %s -- the kernel would run without a model" % bad

    # The kernel is not submittable until this commit run finishes and leaves an output behind,
    # which is exactly the precondition v7.3 now fails.
    status = None
    for i in range(90):
        time.sleep(60)
        try:
            st = api.kernels_status(SLUG)
            status = st.get("status") if isinstance(st, dict) else getattr(st, "status", str(st))
            print("  [%d min] %s" % (i + 1, status), flush=True)
            s = str(status).upper()
            if "COMPLETE" in s or "ERROR" in s or "CANCEL" in s:
                break
        except Exception as e:
            print("  status err %s" % str(e)[:120], flush=True)
    print("final status: %s" % status, flush=True)
    ok = status and "COMPLETE" in str(status).upper()
    print("SUBMITTABLE TOMORROW" if ok else "NOT SUBMITTABLE, the commit run did not complete")
    return bool(ok)


if __name__ == "__main__":
    sys.exit(0 if main() else 1)
